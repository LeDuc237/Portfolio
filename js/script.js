let currentLang = 'fr';

function applyTranslations(lang) {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = translations[lang]?.[key];
    if (value !== undefined) {
      el.innerHTML = value;
    }
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-switch button, .lang-switch-header button').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

function setLang(lang) {
  currentLang = lang;
  applyTranslations(lang);
  typeTerminal(lang);
}

function initLangSwitch() {
  document.querySelectorAll('.lang-switch button, .lang-switch-header button').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang')));
  });
}

function typeTerminal(lang) {
  const el = document.getElementById('typedTerminal');
  if (!el) return;
  el.innerHTML = '';
  const tokens = terminalLines[lang] || terminalLines.fr;
  let i = 0;
  let buffer = '';

  function renderToken(tok) {
    if (tok.t === 'nl') return '<br>';
    if (tok.t === 'indent') return '&nbsp;&nbsp;';
    return `<span class="${tok.t}">${tok.v.replace(/</g, '&lt;')}</span>`;
  }

  function step() {
    if (i >= tokens.length) {
      el.innerHTML = buffer + '<span class="caret"></span>';
      return;
    }
    buffer += renderToken(tokens[i]);
    el.innerHTML = buffer + '<span class="caret"></span>';
    i++;
    const delay = tokens[i - 1] && tokens[i - 1].t === 'nl' ? 90 : 18;
    setTimeout(step, delay);
  }
  step();
}

function initScrollSpy() {
  const sections = ['hero', 'about', 'skills', 'projects', 'journey', 'contact']
    .map(id => document.getElementById(id))
    .filter(Boolean);
  const allTabs = document.querySelectorAll('.tab:not(.mobile-menu .tab)');

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const id = entry.target.id;
        allTabs.forEach(tab => {
          tab.classList.toggle('active', tab.getAttribute('href') === '#' + id);
        });
      }
    });
  }, { rootMargin: '-40% 0px -50% 0px', threshold: 0 });

  sections.forEach(s => observer.observe(s));
}

function initMobileMenu() {
  const toggle = document.getElementById('menuToggle');
  const menu = document.getElementById('mobileMenu');
  if (!toggle || !menu) return;
  toggle.addEventListener('click', () => menu.classList.toggle('open'));
  menu.querySelectorAll('a').forEach(a => a.addEventListener('click', () => menu.classList.remove('open')));
}

function initReveal() {
  const items = document.querySelectorAll('.reveal');
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('in');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  items.forEach(el => observer.observe(el));
}

function initContactForm() {
  const form = document.getElementById('contactForm');
  if (!form) return;
  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const name = form.name.value.trim();
    const email = form.email.value.trim();
    const message = form.message.value.trim();
    if (!name || !email || !message) return;
    const subject = encodeURIComponent(`Contact portfolio — ${name}`);
    const body = encodeURIComponent(`${message}\n\n—\n${name}\n${email}`);
    window.location.href = `mailto:ducheldecarte@gmail.com?subject=${subject}&body=${body}`;
  });
}

